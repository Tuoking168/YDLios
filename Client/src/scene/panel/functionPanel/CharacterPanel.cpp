	if (itToubao != userItem->data.end())
	{
		toubaoValue = itToubao->second;
	}

	
	// 1. Create item icon
	CCMenuItemImage* icon = CommonFunction::getItemIcon(userItem, false);
	icon->setTarget(this, menu_selector(CharacterPanel::itemClickCallBack));
